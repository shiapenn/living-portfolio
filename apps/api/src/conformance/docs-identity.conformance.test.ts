import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, existsSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';

const ROOT = resolve(import.meta.dirname, '../../../..');
const DOCS_CHECK = resolve(ROOT, 'scripts/docs-check');
const DOCS_NEW = resolve(ROOT, 'scripts/docs-new');

describe('Documentation Identity & Registry Conformance (IAHP Section 11 Step 1)', () => {
  let tempDir: string;
  let tempDocsDir: string;
  let tempRegistryPath: string;
  let tempIndexPath: string;

  beforeEach(() => {
    tempDir = mkdtempSync(join(tmpdir(), 'docs-identity-test-'));
    tempDocsDir = join(tempDir, 'docs');
    mkdirSync(tempDocsDir, { recursive: true });
    tempRegistryPath = join(tempDocsDir, 'doc-registry.json');
    tempIndexPath = join(tempDocsDir, 'INDEX.md');
  });

  afterEach(() => {
    if (existsSync(tempDir)) {
      rmSync(tempDir, { recursive: true, force: true });
    }
  });

  function runDocsCheck(args: string[] = []): { stdout: string; stderr: string; status: number } {
    try {
      const stdout = execFileSync('node', [DOCS_CHECK, ...args], {
        cwd: ROOT,
        encoding: 'utf8',
        stdio: 'pipe',
      });
      return { stdout, stderr: '', status: 0 };
    } catch (err: any) {
      return {
        stdout: err.stdout ? err.stdout.toString() : '',
        stderr: err.stderr ? err.stderr.toString() : '',
        status: err.status ?? 1,
      };
    }
  }

  function runDocsNew(args: string[] = []): { stdout: string; stderr: string; status: number } {
    try {
      const stdout = execFileSync('node', [DOCS_NEW, ...args], {
        cwd: ROOT,
        encoding: 'utf8',
        stdio: 'pipe',
      });
      return { stdout, stderr: '', status: 0 };
    } catch (err: any) {
      return {
        stdout: err.stdout ? err.stdout.toString() : '',
        stderr: err.stderr ? err.stderr.toString() : '',
        status: err.status ?? 1,
      };
    }
  }

  function setupValidFixture() {
    const fileA = join(tempDocsDir, 'A001.md');
    const fileP = join(tempDocsDir, 'P001-protocol-fixture-guide.md');
    writeFileSync(fileA, '# Execution Report A001\n\nContent\n', 'utf8');
    writeFileSync(fileP, '# P001 — Protocol fixture guide\n\nContent\n', 'utf8');

    const registry = [
      {
        id: 'A001',
        title: 'Historical Baseline and Tagging',
        class: 'A',
        path: 'docs/A001.md',
        status: 'frozen',
        supersedes: null,
        sha256: '8b7d90d81a942fa722a44a1415df84b7264a780e9a7e6ec38f2a58406f52e557', // sha256 of fileA
      },
      {
        id: 'P001',
        title: 'Protocol fixture guide',
        class: 'P',
        path: 'docs/P001-protocol-fixture-guide.md',
        status: 'active',
        supersedes: null,
      },
    ];

    writeFileSync(tempRegistryPath, JSON.stringify(registry, null, 2), 'utf8');

    // Generate valid INDEX.md
    const indexContent = `# Living Portfolio Documentation Index

<!-- This file is auto-generated by scripts/docs-index from docs/doc-registry.json. Do not edit manually. -->

## Execution Reports & Receipts (Class A)

| ID | Title | Status | File | Supersedes |
| :--- | :--- | :--- | :--- | :--- |
| \`A001\` | Historical Baseline and Tagging | \`frozen\` | [A001.md](A001.md) | — |

## Handover Snapshots (Class H)

*(No entries)*

## Plans & Protocols (Class P)

| ID | Title | Status | File | Supersedes |
| :--- | :--- | :--- | :--- | :--- |
| \`P001\` | Protocol fixture guide | \`active\` | [P001-protocol-fixture-guide.md](P001-protocol-fixture-guide.md) | — |

## Guides, References & Templates (Class G)

*(No entries)*

## Grandfathered Legacy Documents (Class L)

*(No entries)*

`;
    writeFileSync(tempIndexPath, indexContent, 'utf8');
  }

  it('validates active repository documentation without error', () => {
    const res = runDocsCheck();
    expect(res.status).toBe(0);
    expect(res.stdout).toContain('All 28 registered documents validated');
    expect(res.stdout).toContain('docs-check PASSED');
  });

  it('detects duplicate document IDs', () => {
    setupValidFixture();
    const registry = JSON.parse(readFileSync(tempRegistryPath, 'utf8'));
    registry.push({
      id: 'P001', // duplicate
      title: 'Another Duplicate Protocol Guide',
      class: 'P',
      path: 'docs/P001-protocol-fixture-guide.md',
      status: 'active',
      supersedes: null,
    });
    writeFileSync(tempRegistryPath, JSON.stringify(registry, null, 2), 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain("Duplicate ID 'P001'");
  });

  it('detects missing or over-long title (> 80 characters)', () => {
    setupValidFixture();
    const registry = JSON.parse(readFileSync(tempRegistryPath, 'utf8'));
    registry[1].title = 'A'.repeat(81);
    writeFileSync(tempRegistryPath, JSON.stringify(registry, null, 2), 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('Title exceeds 80 characters');
  });

  it('detects filename and H1 mismatch', () => {
    setupValidFixture();
    const fileP = join(tempDocsDir, 'P001-protocol-fixture-guide.md');
    writeFileSync(fileP, '# P001 — Mismatched Heading Title\n\nContent\n', 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('Heading mismatch in');
  });

  it('detects a gap in a class sequence', () => {
    setupValidFixture();
    const fileP2 = join(tempDocsDir, 'P003-third-protocol-document.md');
    writeFileSync(fileP2, '# P003 — Third protocol document\n\nContent\n', 'utf8');

    const registry = JSON.parse(readFileSync(tempRegistryPath, 'utf8'));
    registry.push({
      id: 'P003', // gap: P002 is missing!
      title: 'Third protocol document',
      class: 'P',
      path: 'docs/P003-third-protocol-document.md',
      status: 'active',
      supersedes: null,
    });
    writeFileSync(tempRegistryPath, JSON.stringify(registry, null, 2), 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('Class P sequence has a gap');
  });

  it('detects an edited frozen file whose sha256 does not match', () => {
    setupValidFixture();
    const fileA = join(tempDocsDir, 'A001.md');
    writeFileSync(fileA, '# Execution Report A001\n\nMODIFIED_CONTENT\n', 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('Frozen document');
    expect(res.stderr).toContain('modified');
  });

  it('detects INDEX drift when docs/INDEX.md is out of sync with registry', () => {
    setupValidFixture();
    writeFileSync(tempIndexPath, '# Outdated Index\n\nDoes not match\n', 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('INDEX.md has drifted');
  });

  it('detects unindexed markdown files in docs/', () => {
    setupValidFixture();
    const rogueFile = join(tempDocsDir, 'unindexed-note.md');
    writeFileSync(rogueFile, '# Rogue note\n', 'utf8');

    const res = runDocsCheck([
      '--root', tempDir,
      '--registry', tempRegistryPath,
      '--index', tempIndexPath,
      '--docs-dir', tempDocsDir,
    ]);
    expect(res.status).toBe(1);
    expect(res.stderr).toContain('Unindexed markdown document found');
  });

  it('allocates new document IDs with sequential increment via docs:new', () => {
    setupValidFixture();
    const res = runDocsNew([
      'P',
      'Second protocol document',
      '--slug', 'second-protocol-document',
      '--root', tempDir,
      '--registry', tempRegistryPath,
    ]);

    expect(res.status).toBe(0);
    expect(res.stdout).toContain('Allocated document P002: Second protocol document');
    expect(existsSync(join(tempDir, 'docs/plans/P002-second-protocol-document.md'))).toBe(true);

    const updatedRegistry = JSON.parse(readFileSync(tempRegistryPath, 'utf8'));
    expect(updatedRegistry.find((d: any) => d.id === 'P002')).toBeDefined();
  });
});
